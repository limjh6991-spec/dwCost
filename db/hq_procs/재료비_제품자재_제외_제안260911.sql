   ■ 대상 데이터 (202608)
     08월 품목별투입조회 자재품목자산분류 분포
       약액 88 / 원자재 46 / 부자재 34 / 수탁자재 22 / 제품 1
     '제품' 1건 = 제품번호 7073P ← 자재번호 7073R
       투입수량 258 / 단가 31,573.96511 / 투입금액 8,146,083 / 계정 '원재료비(제조)'
     7073R 은 RMA 반품품이다. 8월에 258개가 반품 입고되어 7073P 생산에 재투입됐다.
     (DOI_STOCK 7073R RMA_AMT 3,565,861 / DOI_PROD_SUBUL 7073P 기타입고_RMA_RW 258 과 같은 흐름)

     DOI_MATL_RESC 202608 품목자산분류별 투입금액
       원자재 307,266,578 / 약액 219,085,346 / 부자재 135,523,512 / 제품 8,146,083 / 카세트제품 0
       합계 670,021,519  (= 품목별투입조회 총계와 정확히 일치)
     품목자산분류='제품' 이면서 투입금액<>0 인 행은 7073R 하나뿐이다.

   ■ 왜 빼야 하는가
     반품품은 이미 제품원가가 매겨진 재고다. 이것을 다시 재료비로 잡으면
     같은 원가가 두 번 계상된다. 재고 간 대체(제품 → 재공)이지 원가 발생이 아니다.

   ■ 소급 영향 없음
     DOI_MATL_RESC 전 기간에서 품목자산분류='제품' 이면서 투입금액<>0 인 달은 202608 이 유일하다.
     202607 doi_mat_amt 의 mat_gubun 분포도 원자재/약액/부자재 3종뿐(제품 0건)이다.
     즉 이번이 최초 발생이며 과거 월 재결산이 필요 없다.

   ============================================================================
   ■ 집계 체인과 제외 지점
   ============================================================================
     DOI_MATL_RESC ─(UP_DOI_MAT_AMT)→ doi_mat_amt ─(UP_DOI_MAT_COST)→ doi_mat_cost → DOI_COST

     mat_gubun 의 원천은 UP_DOI_MAT_AMT L114 :  a.품목자산분류 mat_gubun
       (L103~L145 : INSERT INTO doi_mat_amt ... SELECT sum(투입금액) in_amt, a.품목자산분류 mat_gubun
                    FROM DOI_MATL_RESC a ... HAVING sum(투입금액) != 0)

     UP_DOI_MAT_COST 에는 이미 카세트 제외가 두 곳 있다.
       L541 (MAT_DISTRATE = BOM 직과 경로)   : and a.mat_gubun != '카세트제품'
       L717 (MAT_COMM_RATE = 공통 면적배부)  : and a.mat_gubun != '카세트제품'

   ■ 두 가지 안
     (안A) 상류 UP_DOI_MAT_AMT 에서 제외  → 집계 총액 자체가 줄어든다. 배부는 자동으로 따라온다.
     (안B) UP_DOI_MAT_COST 의 기존 mat_gubun 필터에 '제품' 추가 → 배부에서만 빠지고
           doi_mat_amt 집계 총액에는 8,146,083 이 그대로 남는다.

     사용자 요구는 "집계 및 배부 둘 다" 이므로 **안A 가 정답**이다.
     다만 안A 만 적용하면 UP_DOI_MAT_AMT 자체 검증이 8,146,083 차이를 불일치로 보고하므로
     **검증식도 같은 조건으로 맞춰야 한다**(아래 (2)).
     안B 는 **적용하지 않는다** — 과거 월(202510 등)에 정상 원·부자재가 mat_gubun='제품' 으로
     남아 있어 재실행 시 250,871,934 가 소실된다. 상세는 (3) 참조.

