BEGIN
  COMMIT;
  SELECT N'DOI_STOCK breakdown 정정 완료' AS 결과,
         @c1 AS 기타입고행, @c2 AS OUT_ETC행, @c3 AS RMA행,
         @etcin AS 기타입고합, @outetc AS OUT_ETC합, @rma AS RMA합계,
         @inbad AS 입고위반, @outbad AS 출고위반;
  SELECT MODEL, MODEL_TYPE, STOCK, [INPUT], [OUT], 기타입고, OUT_ETC, RMA_AMT
    FROM DOI_STOCK WHERE YYYYMM='202608' AND SITE='HQ' AND MODEL_TYPE LIKE '%R'
   ORDER BY MODEL_TYPE;
END
ELSE
BEGIN
  ROLLBACK;
  SELECT N'검증 실패 — 원상복구' AS 결과, @msg AS 사유;
END
GO
